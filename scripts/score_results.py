"""Compare a differential expression result with the known composition of the dataset.

The dataset in data/ was generated by scripts/make_data.py from a specified
model, so the set of genes that really differ between the two conditions is
known. This script compares your result with that list.

This measures the analysis, not the analyst. A result that recovers fewer genes
is not a mistake. It usually means that a defensible decision somewhere in the
pipeline cost some statistical power. The useful question is which decision.

Usage:
    python scripts/score_results.py results/de_results.tsv
    python scripts/score_results.py results/de_results.tsv --padj 0.05 --lfc 1.0

The input file must contain the columns gene_symbol, log2_fold_change and padj.
Common variants of those names are accepted.
"""

import argparse
import json
from pathlib import Path

import numpy as np
import pandas as pd

from enrich import resolve_columns  # same directory

ROOT = Path(__file__).resolve().parent.parent
KEY = ROOT / "solutions" / "answer_key.tsv"
BENCHMARK = ROOT / "solutions" / "reference_outputs" / "benchmark.json"

BAR_WIDTH = 40


def bar(value, maximum):
    filled = int(round(BAR_WIDTH * value / maximum)) if maximum else 0
    return "#" * filled + "." * (BAR_WIDTH - filled)


def main():
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("results", help="your differential expression results table")
    parser.add_argument("--padj", type=float, default=0.05,
                        help="adjusted p-value threshold you used")
    parser.add_argument("--lfc", type=float, default=1.0,
                        help="minimum absolute log2 fold change you used")
    args = parser.parse_args()

    if not KEY.exists():
        raise SystemExit(
            f"Cannot find {KEY}. Run 'python scripts/make_data.py' first.")

    sep = "\t" if args.results.endswith((".tsv", ".txt")) else ","
    results = pd.read_csv(args.results, sep=sep)
    cols = resolve_columns(results)
    table = results[[cols["gene_symbol"], cols["log2_fold_change"], cols["padj"]]].copy()
    table.columns = ["gene_symbol", "log2_fold_change", "padj"]

    key = pd.read_csv(KEY, sep="\t")
    total_true = int(key["is_differential"].sum())

    merged = table.merge(
        key[["gene_symbol", "true_log2_fold_change", "is_differential"]],
        on="gene_symbol", how="left")
    unmatched = int(merged["is_differential"].isna().sum())
    merged["is_differential"] = merged["is_differential"].fillna(0)

    called = (merged["padj"] < args.padj) & (merged["log2_fold_change"].abs() >= args.lfc)
    truth = merged["is_differential"] == 1

    tp = int((called & truth).sum())
    fp = int((called & ~truth).sum())
    missed = total_true - tp

    print()
    print("Comparison with the known composition of the dataset")
    print("=" * 62)
    print(f"File tested:  {args.results}")
    print(f"Genes in your table: {len(table)}"
          + (f"   ({unmatched} symbols not found in the key)" if unmatched else ""))
    print(f"Thresholds:   adjusted p < {args.padj}, "
          f"absolute log2 fold change >= {args.lfc}")
    print()
    print(f"The dataset contains {total_true} genes that really differ "
          f"between the conditions.")
    print()
    print(f"  Found        {tp:4d}  {bar(tp, total_true)}")
    print(f"  Missed       {missed:4d}  {bar(missed, total_true)}")
    print(f"  False alarms {fp:4d}  genes you called that do not really differ")
    print()
    print(f"  Of the genes you called, {100 * tp / max(tp + fp, 1):.0f} per cent are real.")
    print(f"  Of the genes that are real, you found {100 * tp / total_true:.0f} per cent.")

    both = merged.loc[truth & merged["true_log2_fold_change"].notna()]
    if len(both) > 2:
        agreement = (np.sign(both["log2_fold_change"])
                     == np.sign(both["true_log2_fold_change"])).mean()
        correlation = np.corrcoef(both["log2_fold_change"],
                                  both["true_log2_fold_change"])[0, 1]
        print()
        print("  For the genes that really differ:")
        print(f"    direction correct in {100 * agreement:.0f} per cent of them")
        print(f"    correlation between your effect size and the true effect "
              f"size: {correlation:.2f}")

    if BENCHMARK.exists():
        marks = json.loads(BENCHMARK.read_text())
        print()
        print("Two reference analyses of the same data, for comparison")
        print("-" * 62)
        print(f"  {'analysis':34s} {'found':>6s} {'false alarms':>13s}")
        labels = {
            "condition_only": "condition only",
            "condition_and_batch": "condition and batch in the model",
        }
        for name, values in marks.items():
            print(f"  {labels.get(name, name):34s} "
                  f"{values['true_positives']:6d} {values['false_positives']:13d}")
        print(f"  {'your analysis':34s} {tp:6d} {fp:13d}")
        print()
        print("  The two reference analyses differ in one respect only. The second")
        print("  includes the processing batch in the statistical model. Adding it")
        print("  removes a source of variation that is not the treatment, which")
        print("  leaves more power to detect the treatment effect.")

    print()
    print("Questions worth asking about your own number")
    print("-" * 62)
    print("  Which filtering threshold did you use, and how many genes did it remove?")
    print("  Which normalization method was used, and why that one?")
    print("  Was the processing batch used anywhere in the analysis?")
    print("  Did you set the fold change threshold before or after seeing the result?")
    print()
    print("  A lower count is not a failure. Find the decision that caused it.")
    print()


if __name__ == "__main__":
    main()
